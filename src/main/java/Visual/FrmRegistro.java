    private void tblClienteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClienteMouseClicked
        int selectedRow = tblCliente.getSelectedRow();

        if (btnActualizar.isEnabled()) {
            if (selectedRow != -1) {
                String id = tblCliente.getValueAt(selectedRow, 0).toString();
                String fecha = tblCliente.getValueAt(selectedRow, 1).toString();
                String nombre = tblCliente.getValueAt(selectedRow, 2).toString();
                String cedula = tblCliente.getValueAt(selectedRow, 3).toString();
                String email = tblCliente.getValueAt(selectedRow, 4).toString();
                String direccion = tblCliente.getValueAt(selectedRow, 5).toString();
                String tipoPago = tblCliente.getValueAt(selectedRow, 6).toString();

                txtIDCliente.setText(id);
                txtNombre.setText(nombre);
                txtCedula.setText(cedula);
                txtEmail.setText(email);
                txtDireccion.setText(direccion);
                try {
                    Date date = new SimpleDateFormat("yyyy-MM-dd").parse(fecha);
                    dtcFecha.setDate(date);
                } catch (ParseException ex) {
                    ex.printStackTrace();
                }

                if (tipoPago.equals("Tarjeta")) {
                    rdbTarjeta.setSelected(true);
                } else if (tipoPago.equals("Efectivo")) {
                    rdbEfectivo.setSelected(true);
                }
            } else {
                JOptionPane.showMessageDialog(null, "Por favor seleccione una fila para editar.");
            }

        }
    }//GEN-LAST:event_tblClienteMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        java.util.Date dFecha = dtcFecha.getDate();
        java.sql.Date dFechareg = new java.sql.Date(dFecha.getTime());

        String id = txtIDCliente.getText().trim();
        int idCliente = Integer.parseInt(id);
        String nombre = txtNombre.getText().trim();
        String cedula = txtCedula.getText().trim();
        String email = txtEmail.getText().trim();
        String direccion = txtDireccion.getText().trim();
        String pago = "";
        boolean tipoPago = false;
        if (rdbTarjeta.isSelected()) {
            tipoPago = true;
            pago = rdbTarjeta.getText();
        } else if (rdbEfectivo.isSelected()) {
            tipoPago = false;
            pago = rdbEfectivo.getText();
        }
        adm.editar(idCliente, dFechareg, nombre, cedula, email, direccion, pago);
        JOptionPane.showMessageDialog(null, "Datos actualizados");
        txtIDCliente.setText("");
        txtNombre.setText("");
        txtCedula.setText("");
        txtEmail.setText("");
        txtDireccion.setText("");
        dtcFecha.setDate(null);
        rdbTarjeta.setSelected(false);
        rdbEfectivo.setSelected(false);
        btnAgregar.setEnabled(false);
        btnEliminar.setEnabled(true);
        btnActualizar.setEnabled(false);
        adm.llenarTabla(tblCliente, lblTotal);

    }//GEN-LAST:event_btnActualizarActionPerformed

