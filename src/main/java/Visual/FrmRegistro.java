    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        java.util.Date dFecha = dtcFecha.getDate();
        java.sql.Date dFechareg = new java.sql.Date(dFecha.getTime());

        String nombre = txtNombre.getText().trim();
        String cedula = txtCedula.getText().trim();
        String email = txtEmail.getText().trim();
        String direccion = txtDireccion.getText().trim();
        String pago = "";
        boolean tipoPago = false;
        if (rdbTarjeta.isSelected()) {
            tipoPago = true;
            pago = rdbTarjeta.getText();
        } else if (rdbEfectivo.isSelected()) {
            tipoPago = false;
            pago = rdbEfectivo.getText();
        }
        String contenido = "";
        if (nombre.compareTo("") != 0 && cedula.compareTo("") != 0 && email.compareTo("") != 0
                && direccion.compareTo("") != 0 && dFechareg != null && rdbTarjeta.isSelected() == true
                || rdbEfectivo.isSelected() == true) {
            adm.ingresar(dFechareg, nombre, cedula, email, direccion, pago);
            JOptionPane.showMessageDialog(null, "Datos ingresados correctamente");
            txtNombre.setText("");
            txtCedula.setText("");
            txtEmail.setText("");
            txtDireccion.setText("");
            dtcFecha.setDate(null);
            rdbTarjeta.setSelected(false);
            rdbEfectivo.setSelected(false);
            btnAgregar.setEnabled(false);
            btnEliminar.setEnabled(true);
            adm.llenarTabla(tblCliente, lblTotal);
        } else {
            JOptionPane.showMessageDialog(null, "Existen campos vacios");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

